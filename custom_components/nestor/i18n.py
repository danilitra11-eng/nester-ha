def pick_language(configured: str, ui_language: str | None = None) -> str:
    """Configured language wins; with "auto", use the browser's language."""
    if configured in SUPPORTED:
        return configured
    if ui_language:
        code = ui_language.lower().split("-")[0]
        if code in SUPPORTED:
            return code
    return "en"


def localize(code: str, language: str, detail: dict[str, Any] | None = None) -> str:
    entry = MESSAGES.get(code, MESSAGES["generic"])
    text = entry.get(language, entry["en"])
    return text.format(renew_url=(detail or {}).get("renew_url", ""))
