"""Dashboard and theme tools. Every change is backed up first and can be undone."""

from __future__ import annotations

import copy
import inspect
import json
import re
import time
from typing import Any

from homeassistant.core import HomeAssistant
from homeassistant.helpers.storage import Store

from .tools_home import ToolError

MAX_BACKUPS = 10
DEFAULT_KEY = "__default__"  # the main "Overview" dashboard (url_path None)


def _slug(text: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s or "home"


class DesignTools:
    def __init__(self, hass: HomeAssistant, entry_id: str) -> None:
        self.hass = hass
        self._store: Store[dict[str, Any]] = Store(hass, 1, f"nestor.design.{entry_id}")
        self._data: dict[str, Any] = {"created": [], "backups": {}}

    async def async_load(self) -> None:
        self._data = await self._store.async_load() or {"created": [], "backups": {}}

    def _save(self) -> None:
        self._store.async_delay_save(lambda: self._data, 1)

    # ---- lovelace access ------------------------------------------------

    def _lovelace(self):
        from homeassistant.components.lovelace.const import LOVELACE_DATA

        data = self.hass.data.get(LOVELACE_DATA)
        if data is None:
            raise ToolError("Dashboards are not available in this Home Assistant.")
        return data

    def _dashboard(self, url_path: str | None):
        key = None if url_path in (None, "", "lovelace", DEFAULT_KEY) else url_path
        dash = self._lovelace().dashboards.get(key)
        if dash is None:
            raise ToolError(f"No dashboard '{url_path}'. Use list_dashboards.")
        if getattr(dash, "mode", "storage") != "storage":
            raise ToolError("That dashboard is managed in YAML files and can't be edited here.")
        return key, dash

    def _collection(self):
        """The storage collection behind Settings > Dashboards (to create real dashboards)."""
        from homeassistant.components.websocket_api.const import DOMAIN as WS_DOMAIN

        handler = self.hass.data.get(WS_DOMAIN, {}).get("lovelace/dashboards/create", (None,))[0]
        bound = inspect.unwrap(handler) if handler else None
        coll = getattr(getattr(bound, "__self__", None), "storage_collection", None)
        if coll is None:
            raise ToolError("Creating dashboards isn't supported on this Home Assistant version.")
        return coll

    async def _load(self, url_path: str | None) -> dict[str, Any]:
        _, dash = self._dashboard(url_path)
        try:
            return await dash.async_load(False)
        except Exception:  # ConfigNotFound: auto-generated dashboard with no saved config
            return {}

    async def _backup(self, url_path: str | None) -> None:
        key = url_path or DEFAULT_KEY
        current = await self._load(url_path)
        stack = self._data["backups"].setdefault(key, [])
        stack.append({"at": int(time.time()), "config": current})
        del stack[:-MAX_BACKUPS]
        self._save()

    def is_nestor_dashboard(self, url_path: str | None) -> bool:
        return url_path in self._data["created"]

    # ---- tools ----------------------------------------------------------

    async def list_dashboards(self) -> str:
        out = []
        for key, dash in self._lovelace().dashboards.items():
            cfg = getattr(dash, "config", None) or {}
            out.append({"url_path": key or "lovelace", "title": cfg.get("title") or "Overview",
                        "mode": getattr(dash, "mode", "storage"),
                        "created_by_nestor": key in self._data["created"]})
        return json.dumps({"dashboards": out}, ensure_ascii=False)

    async def get_dashboard(self, url_path: str) -> str:
        cfg = await self._load(url_path)
        text = json.dumps(cfg, ensure_ascii=False)
        if not cfg:
            return json.dumps({"note": "This dashboard is auto-generated by Home Assistant and has "
                               "no saved layout yet."})
        return text[:30000]

    async def create_dashboard(self, title: str, icon: str | None, config: dict[str, Any]) -> str:
        if not isinstance(config, dict) or not isinstance(config.get("views"), list):
            raise ToolError('config must be a Lovelace config object with a "views" list.')
        base = f"nestor-{_slug(title)}"
        url_path, n = base, 2
        while url_path in self._lovelace().dashboards:
            url_path, n = f"{base}-{n}", n + 1
        item: dict[str, Any] = {"url_path": url_path, "title": title, "show_in_sidebar": True,
                                "require_admin": False}
        if icon:
            item["icon"] = icon
        try:
            await self._collection().async_create_item(item)
        except Exception as err:
            raise ToolError(f"Couldn't create the dashboard: {err}") from err
        _, dash = self._dashboard(url_path)
        await dash.async_save(config)
        self._data["created"].append(url_path)
        self._save()
        return json.dumps({"ok": True, "url_path": url_path, "open": f"/{url_path}"})

    async def save_dashboard(self, url_path: str, config: dict[str, Any]) -> str:
        if not isinstance(config, dict) or not isinstance(config.get("views"), list):
            raise ToolError('config must be a Lovelace config object with a "views" list.')
        key, dash = self._dashboard(url_path)
        await self._backup(key)
        await dash.async_save(copy.deepcopy(config))
        return json.dumps({"ok": True, "url_path": key or "lovelace",
                           "note": "Previous version saved; undo_dashboard restores it."})

    async def undo_dashboard(self, url_path: str) -> str:
        key, dash = self._dashboard(url_path)
        stack = self._data["backups"].get(key or DEFAULT_KEY) or []
        if not stack:
            raise ToolError("There is no earlier version of this dashboard to go back to.")
        previous = stack.pop()
        self._save()
        if previous["config"]:
            await dash.async_save(previous["config"])
        else:
            await dash.async_delete()  # back to auto-generated
        return json.dumps({"ok": True, "restored_from": previous["at"],
                           "earlier_versions_left": len(stack)})

    async def delete_dashboard(self, url_path: str) -> str:
        if url_path not in self._data["created"]:
            raise ToolError("I can only delete dashboards that I created.")
        coll = self._collection()
        for item_id, item in list(coll.data.items()):
            if item.get("url_path") == url_path:
                await coll.async_delete_item(item_id)
        self._data["created"].remove(url_path)
        self._save()
        return json.dumps({"ok": True, "deleted": url_path})

    async def list_themes(self) -> str:
        from homeassistant.components.frontend import DATA_THEMES

        themes = sorted((self.hass.data.get(DATA_THEMES) or {}).keys())
        return json.dumps({"themes": ["default", *themes],
                           "note": "More themes can be installed from the Marketplace."})

    async def set_theme(self, name: str, mode: str | None = None) -> str:
        data: dict[str, Any] = {"name": name}
        if mode in ("light", "dark"):
            data["mode"] = mode
        await self.hass.services.async_call("frontend", "set_theme", data, blocking=True)
        return json.dumps({"ok": True, "theme": name, "mode": mode or "both"})
